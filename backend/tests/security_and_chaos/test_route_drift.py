"""A new or removed endpoint must be a decision, not an accident: the list of every route is kept in routes.snapshot.txt. The matrix test (test_bac_matrix.py) rewrites its own
output every run, so it could never notice a new route; this one compares with a committed list. To accept a change, run the matrix test, review the new rows of
docs/ENDPOINT_MATRIX.md, and regenerate the list (see the message below)."""
import pathlib

from tests.security_and_chaos._helpers import operations

SNAPSHOT = pathlib.Path(__file__).with_name("routes.snapshot.txt")


def test_every_route_is_in_the_reviewed_list():
    live = {f"{m} {r.path}" for r, m in operations()}
    known = {line.strip() for line in SNAPSHOT.read_text(encoding="utf-8").splitlines() if line.strip()}
    added, removed = sorted(live - known), sorted(known - live)
    assert not added and not removed, (
        "The endpoints changed. Check who may call each new one (docs/ENDPOINT_MATRIX.md is regenerated by test_bac_matrix.py), then add it to routes.snapshot.txt.\n"
        f"NEW: {added}\nGONE: {removed}")
