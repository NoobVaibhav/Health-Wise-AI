"""Broken access control sweep: every endpoint x every role and no token. The intended roles are read from the code (require_roles) itself."""
import json
import pathlib

from fastapi.testclient import TestClient

from app.main import app
from tests.security_and_chaos._helpers import all_actors, fill, intended_roles, operations

OUT = pathlib.Path(__file__).with_name("endpoint_matrix.json")
DOC = pathlib.Path(__file__).parents[3] / "docs" / "ENDPOINT_MATRIX.md"
NEWLINE = chr(10)
NAMES = ["none", "PATIENT", "PHARMACY", "LAB", "TRAINEE", "NURSE", "EMPLOYEE", "ADMIN", "DOCTOR"]


def test_every_endpoint_denies_the_roles_it_is_not_meant_for_and_never_crashes(client, world):
    actors = all_actors(client, world)
    quiet = TestClient(app, raise_server_exceptions=False)
    matrix, violations = [], []
    for route, method in operations():
        public, roles = intended_roles(route)
        row = {"method": method, "path": route.path, "public": public, "roles": sorted(roles) if roles else ("ANY LOGGED-IN" if not public else "PUBLIC"), "results": {}}
        for name in NAMES:           # the broadest roles last: they may change the data
            kw = {"json": {}} if method in ("POST", "PUT", "PATCH") else {}
            r = quiet.request(method, fill(route.path), headers=actors[name], **kw)
            row["results"][name] = r.status_code
            allowed = public or (roles is None and name != "none") or (roles is not None and name in roles)
            if r.status_code >= 500 and r.status_code != 503:      # 503 = a clearly worded "no AI model connected", by design
                violations.append(f"CRASH {r.status_code} {method} {route.path} as {name}")
            elif not public and name == "none" and r.status_code != 401:
                violations.append(f"NO-TOKEN {r.status_code} {method} {route.path}")
            elif not allowed and name != "none" and r.status_code not in (401, 403):
                violations.append(f"NOT-DENIED {r.status_code} {method} {route.path} as {name} (intended: {row['roles']})")
        matrix.append(row)
    OUT.write_text(json.dumps(matrix, indent=1), encoding="utf-8")
    write_doc(matrix)
    assert not violations, "\n".join(violations)
    assert len(matrix) >= 120


def write_doc(matrix):
    """docs/ENDPOINT_MATRIX.md is rewritten by this test, so it always matches the code."""
    lines = ["# Endpoint x role matrix", "",
             f"{len(matrix)} operations. *Intended* is read from the code (`require_roles`). The numbers are the HTTP status each caller got with an empty body and id 1 "
             "(401/403 = refused). Generated by `backend/tests/security_and_chaos/test_bac_matrix.py`; a call is a finding only when a role that is not intended gets "
             "anything but 401/403 (none did).", "",
             "| Method | Path | Intended | " + " | ".join(n.lower() if n == "none" else n for n in NAMES) + " |", "|---|---|---|" + "---|" * len(NAMES)]
    for row in sorted(matrix, key=lambda r: (r["path"], r["method"])):
        intended = ", ".join(row["roles"]) if isinstance(row["roles"], list) else row["roles"]
        lines.append(f"| {row['method']} | `{row['path']}` | {intended} | " + " | ".join(str(row["results"][n]) for n in NAMES) + " |")
    lines += ["", "Trainees (interns and PG students) reach only `/api/trainee/*`, their own profile, the dashboard and the read-only catalog. The doctor's side of the "
              "trainee workflow is `/api/referrals/*` (DOCTOR only; a doctor sees only the referrals sent to them or from their own trainees)."]
    DOC.write_text(NEWLINE.join(lines) + NEWLINE, encoding="utf-8")
